import { useEffect, useRef, useState, type FormEvent } from "react";
import { createRoot } from "react-dom/client";
import { ApiError, request } from "./api";
import {
  severities,
  statuses,
  validate,
  modeLabel,
  listQuery,
  type Incident,
  type IncidentPage,
  type Diagnosis,
  type Draft,
  type Statement,
} from "./domain";
import "./style.css";

const date = (value: string) => new Date(value).toLocaleString();
const message = (e: unknown) =>
  e instanceof Error ? e.message : "Unable to reach the server.";
function Badge({ value }: { value: string }) {
  return (
    <span className={"badge " + value.toLowerCase()}>
      {value.replaceAll("_", " ")}
    </span>
  );
}
function DiagnosisView({ diagnosis: d }: { diagnosis: Diagnosis }) {
  const generated = d.mode === "GENERATED";
  const sections: [string, Statement[]][] = [
    ["Likely causes", d.likelyCauses],
    ["Investigation steps", d.investigationSteps],
    ["Suggested remediation", d.suggestedRemediation],
  ];
  return (
    <section aria-label="Diagnosis">
      <div className={"notice " + (generated ? "generated" : "")}>
        <h3>{modeLabel(d.mode)}</h3>
        <p>
          {generated
            ? "Generated by a local model. Review every suggestion against the cited evidence before taking action."
            : d.mode === "RETRIEVAL_ONLY"
              ? "No language model was used. These are retrieved runbook excerpts, not AI-generated analysis or recommended actions."
              : "Historical result with limited provenance."}
        </p>
      </div>
      {generated && (
        <>
          <p>{d.summary}</p>
          <p className="muted">
            {d.provider} · {d.model}
          </p>
          {sections.map(([title, items]) => (
            <section key={title}>
              <h3>{title}</h3>
              {items.length ? (
                <ol>
                  {items.map((s, i) => (
                    <li key={i}>
                      <p>{s.text}</p>
                      <small>Sources: {s.sources.join(", ")}</small>
                    </li>
                  ))}
                </ol>
              ) : (
                <p>No suggestions provided.</p>
              )}
            </section>
          ))}
        </>
      )}
      {d.mode === "LEGACY" && (
        <>
          <p>{d.summary}</p>
          <p className="preserve">{d.recommendations}</p>
        </>
      )}
      {d.uncertainty && <p className="muted">{d.uncertainty}</p>}
      <h3>Cited runbooks</h3>
      <p>
        {d.citedRunbooks.length
          ? d.citedRunbooks.join(" · ")
          : "No citations available."}
      </p>
      <h3>
        Retrieved evidence <small>({d.retrievedEvidence.length} chunks)</small>
      </h3>
      <p className="muted">
        Similarity measures relevance, not confidence. Excerpts are reference
        material; commands are never executed here.
      </p>
      {d.retrievedEvidence.map((e, i) => (
        <details key={e.chunkId + "-" + i}>
          <summary>
            {e.source} <small>· similarity {e.similarity.toFixed(3)}</small>
          </summary>
          <pre>{e.excerpt}</pre>
        </details>
      ))}
    </section>
  );
}
function Detail({ id, close }: { id: string; close: () => void }) {
  const [incident, setIncident] = useState<Incident | null>(null),
    [diagnosis, setDiagnosis] = useState<Diagnosis | null>(null),
    [error, setError] = useState(""),
    [diagnosisError, setDiagnosisError] = useState("");
  useEffect(() => {
    let alive = true;
    let busy = false;
    async function load() {
      if (busy) return;
      busy = true;
      try {
        const i = await request<Incident>("/api/incidents/" + id);
        if (!alive) return;
        setIncident(i);
        setError("");
        try {
          const d = await request<Diagnosis>(
            "/api/incidents/" + id + "/diagnosis",
          );
          if (alive) {
            setDiagnosis(d);
            setDiagnosisError("");
          }
        } catch (e) {
          if (alive) {
            if (e instanceof ApiError && e.status === 404) {
              setDiagnosis(null);
              setDiagnosisError("");
            } else setDiagnosisError(message(e));
          }
        }
      } catch (e) {
        if (alive) setError(message(e));
      } finally {
        busy = false;
      }
    }
    void load();
    const timer = setInterval(() => void load(), 5000);
    return () => {
      alive = false;
      clearInterval(timer);
    };
  }, [id]);
  const heading = useRef<HTMLHeadingElement>(null);
  useEffect(() => {
    heading.current?.focus();
  }, []);
  return (
    <section className="panel detail">
      <button onClick={close}>← Back to incidents</button>
      <h2 tabIndex={-1} ref={heading}>
        Incident details
      </h2>
      {error && (
        <p role="alert" className="error">
          {error} Retrying automatically.
        </p>
      )}
      {!incident && !error && <p role="status">Loading incident…</p>}
      {incident && (
        <>
          <div className="tags">
            <Badge value={incident.severity} />
            <Badge value={incident.status} />
            <span>{incident.service}</span>
          </div>
          <h3 className="incident-title">{incident.title}</h3>
          <dl>
            <dt>Created</dt>
            <dd>{date(incident.createdAt)}</dd>
            <dt>Updated</dt>
            <dd>{date(incident.updatedAt)}</dd>
            <dt>ID</dt>
            <dd className="id">{incident.id}</dd>
          </dl>
          <h3>Description</h3>
          <p className="preserve">{incident.description}</p>
          <hr />
          {diagnosisError && (
            <p role="alert" className="error">
              Diagnosis could not be loaded: {diagnosisError} Retrying
              automatically.
            </p>
          )}
          {diagnosis ? (
            <DiagnosisView diagnosis={diagnosis} />
          ) : (
            !diagnosisError && (
              <div className="notice">
                <h3>
                  {incident.status === "FAILED"
                    ? "Processing failed"
                    : incident.status === "PENDING"
                      ? "Diagnosis pending"
                      : "No diagnosis available"}
                </h3>
                <p>
                  {incident.status === "FAILED"
                    ? "The worker could not complete this incident. Inspect worker logs and quarantine records."
                    : "This view checks for a stored diagnosis every five seconds. Older incidents may have no diagnosis."}
                </p>
              </div>
            )
          )}
        </>
      )}
    </section>
  );
}
function NewIncident({
  created,
  cancel,
}: {
  created: (i: Incident) => void;
  cancel: () => void;
}) {
  const [draft, setDraft] = useState<Draft>({
      service: "",
      title: "",
      description: "",
      severity: "HIGH",
    }),
    [errors, setErrors] = useState<Record<string, string>>({}),
    [error, setError] = useState(""),
    [saving, setSaving] = useState(false);
  const form = useRef<HTMLFormElement>(null);
  useEffect(() => {
    form.current?.querySelector("input")?.focus();
  }, []);
  async function submit(event: FormEvent) {
    event.preventDefault();
    const invalid = validate(draft);
    setErrors(invalid);
    if (Object.keys(invalid).length) {
      requestAnimationFrame(() =>
        form.current
          ?.querySelector<HTMLElement>('[aria-invalid="true"]')
          ?.focus(),
      );
      return;
    }
    setSaving(true);
    setError("");
    try {
      created(
        await request<Incident>("/api/incidents", {
          method: "POST",
          body: JSON.stringify({
            ...draft,
            service: draft.service.trim(),
            title: draft.title.trim(),
            description: draft.description.trim(),
          }),
        }),
      );
    } catch (e) {
      setError(message(e));
    } finally {
      setSaving(false);
    }
  }
  return (
    <section className="panel">
      <h2>Report an incident</h2>
      <p className="muted">
        The local worker retrieves runbooks and stores a diagnosis
        asynchronously.
      </p>
      <form ref={form} noValidate onSubmit={submit}>
        {(["service", "title", "description"] as const).map((field) => (
          <div key={field}><label htmlFor={"new-" + field}>
            {field[0].toUpperCase() + field.slice(1)}
            {field === "description" ? (
              <textarea
                id={"new-" + field}
                required
                maxLength={10000}
                rows={6}
                value={draft[field]}
                aria-invalid={!!errors[field]}
                aria-describedby={errors[field] ? field + "-error" : undefined}
                onChange={(e) =>
                  setDraft({ ...draft, [field]: e.target.value })
                }
              />
            ) : (
              <input
                id={"new-" + field}
                required
                maxLength={field === "service" ? 100 : 200}
                value={draft[field]}
                aria-invalid={!!errors[field]}
                aria-describedby={errors[field] ? field + "-error" : undefined}
                onChange={(e) =>
                  setDraft({ ...draft, [field]: e.target.value })
                }
              />
            )}</label>
            {errors[field] && (
              <span className="field-error" id={field + "-error"}>
                {errors[field]}
              </span>
            )}
          </div>
        ))}
        <label htmlFor="new-severity">
          Severity
          <select
            id="new-severity"
            aria-label="Severity"
            value={draft.severity}
            onChange={(e) => setDraft({ ...draft, severity: e.target.value })}
          >
            {severities.map((s) => (
              <option key={s}>{s}</option>
            ))}
          </select>
        </label>
        {error && (
          <p role="alert" className="error">
            {error} Your input has been retained. Check the incident list before
            retrying if the request timed out.
          </p>
        )}
        <div className="actions">
          <button className="primary" disabled={saving}>
            {saving ? "Submitting…" : "Submit incident"}
          </button>
          <button type="button" onClick={cancel} disabled={saving}>
            Cancel
          </button>
        </div>
      </form>
    </section>
  );
}
function App() {
  const [page, setPage] = useState(0),
    [severity, setSeverity] = useState(""),
    [status, setStatus] = useState(""),
    [service, setService] = useState(""),
    [filterService, setFilterService] = useState(""),
    [data, setData] = useState<IncidentPage | null>(null),
    [error, setError] = useState(""),
    [loading, setLoading] = useState(true),
    [updated, setUpdated] = useState(""),
    [refresh, setRefresh] = useState(0),
    [creating, setCreating] = useState(false),
    [announcement, setAnnouncement] = useState("");
  const [selected, setSelected] = useState(() =>
    new URLSearchParams(location.search).get("incident"),
  );
  function select(id: string | null) {
    setSelected(id);
    const url = new URL(location.href);
    if (id) url.searchParams.set("incident", id);
    else url.searchParams.delete("incident");
    history.pushState(null, "", url);
  }
  useEffect(() => {
    const change = () => {
      setSelected(new URLSearchParams(location.search).get("incident"));
      setCreating(false);
    };
    addEventListener("popstate", change);
    return () => removeEventListener("popstate", change);
  }, []);
  useEffect(() => {
    let alive = true;
    let busy = false;
    setLoading(true);
    setData(null);
    async function load() {
      if (busy) return;
      busy = true;
      try {
        const result = await request<IncidentPage>(
          listQuery(page, severity, status, filterService),
        );
        if (alive) {
          if (result.totalPages > 0 && page >= result.totalPages) {
            setPage(result.totalPages - 1);
            return;
          }
          setData(result);
          setError("");
          setUpdated(new Date().toLocaleTimeString());
        }
      } catch (e) {
        if (alive) setError(message(e));
      } finally {
        busy = false;
        if (alive) setLoading(false);
      }
    }
    void load();
    const timer = setInterval(() => void load(), 10000);
    return () => {
      alive = false;
      clearInterval(timer);
    };
  }, [page, severity, status, filterService, refresh]);
  return (
    <>
      <a href="#main" className="skip">
        Skip to content
      </a>
      <header>
        <a className="brand" href="/">
          Incident<span>IQ</span>
        </a>
        <span className="local">LOCAL WORKSPACE</span>
        <nav aria-label="Monitoring">
          <a
            href="http://localhost:3001/d/incidentiq-overview"
            target="_blank"
            rel="noreferrer"
          >
            Grafana ↗
          </a>
          <a href="http://localhost:9090" target="_blank" rel="noreferrer">
            Prometheus ↗
          </a>
          <a href="http://localhost:9093" target="_blank" rel="noreferrer">
            Alertmanager ↗
          </a>
        </nav>
      </header>
      <main id="main">
        <div className="page-heading">
          <div>
            <p className="eyebrow">OPERATIONS / INCIDENTS</p>
            <h1>Incident workspace</h1>
            <p className="muted">
              Track service issues and investigate with local runbook evidence.
            </p>
          </div>
          <button
            className="primary"
            onClick={() => {
              select(null);
              setCreating(true);
            }}
          >
            + Report incident
          </button>
        </div>
        <p className="sr-only" role="status">
          {announcement}
        </p>
        {creating ? (
          <NewIncident
            cancel={() => setCreating(false)}
            created={(i) => {
              setCreating(false);
              select(i.id);
              setAnnouncement("Incident created successfully.");
              setRefresh((r) => r + 1);
            }}
          />
        ) : selected ? (
          <Detail
            key={selected}
            id={selected}
            close={() => {
              select(null);
              setRefresh((r) => r + 1);
            }}
          />
        ) : (
          <section className="panel" aria-label="Incidents">
            <div className="list-heading">
              <h2>
                Incidents{" "}
                {data && <span className="count">{data.totalElements}</span>}
              </h2>
              <div className="refresh">
                <span>
                  {updated
                    ? "Updated " + updated + " · refreshes every 10s"
                    : "Refreshes every 10s"}
                </span>
                <button onClick={() => setRefresh((r) => r + 1)}>
                  Refresh
                </button>
              </div>
            </div>
            <form
              className="filters"
              onSubmit={(e) => {
                e.preventDefault();
                setPage(0);
                setFilterService(service);
              }}
            >
              <label>
                Severity
                <select
                  aria-label="Severity"
                  value={severity}
                  onChange={(e) => {
                    setSeverity(e.target.value);
                    setPage(0);
                  }}
                >
                  <option value="">All severities</option>
                  {severities.map((s) => (
                    <option key={s}>{s}</option>
                  ))}
                </select>
              </label>
              <label>
                Status
                <select
                  aria-label="Status"
                  value={status}
                  onChange={(e) => {
                    setStatus(e.target.value);
                    setPage(0);
                  }}
                >
                  <option value="">All statuses</option>
                  {statuses.map((s) => (
                    <option key={s}>{s}</option>
                  ))}
                </select>
              </label>
              <label>
                Service
                <input
                  placeholder="Search service name"
                  value={service}
                  maxLength={100}
                  onChange={(e) => setService(e.target.value)}
                />
              </label>
              <button>Apply service</button>
              <button
                type="button"
                onClick={() => {
                  setSeverity("");
                  setStatus("");
                  setService("");
                  setFilterService("");
                  setPage(0);
                }}
              >
                Clear filters
              </button>
            </form>
            {error && (
              <p role="alert" className="error">
                Unable to refresh incidents: {error}{" "}
                {data ? "Showing the last successful result." : ""}{" "}
                <button onClick={() => setRefresh((r) => r + 1)}>Retry</button>
              </p>
            )}
            {loading && <p role="status">Loading incidents…</p>}
            {data && data.content.length === 0 && (
              <div className="empty">
                <h3>No incidents found</h3>
                <p>Try different filters or report a new incident.</p>
              </div>
            )}
            {data && data.content.length > 0 && (
              <>
                <div className="table-scroll">
                  <table>
                    <caption className="sr-only">
                      Incident list, newest first
                    </caption>
                    <thead>
                      <tr>
                        <th>Incident / service</th>
                        <th>Severity</th>
                        <th>Status</th>
                        <th>Created</th>
                        <th>Updated</th>
                      </tr>
                    </thead>
                    <tbody>
                      {data.content.map((i) => (
                        <tr key={i.id}>
                          <td>
                            <button
                              className="incident-link"
                              onClick={() => select(i.id)}
                            >
                              {i.title}
                            </button>
                            <span className="service">{i.service}</span>
                          </td>
                          <td>
                            <Badge value={i.severity} />
                          </td>
                          <td>
                            <Badge value={i.status} />
                          </td>
                          <td>
                            <time dateTime={i.createdAt}>
                              {date(i.createdAt)}
                            </time>
                          </td>
                          <td>
                            <time dateTime={i.updatedAt}>
                              {date(i.updatedAt)}
                            </time>
                          </td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
                <div className="pagination">
                  <span>
                    Page {data.page + 1} of {data.totalPages} ·{" "}
                    {data.totalElements} matching incidents
                  </span>
                  <div className="actions">
                    <button
                      disabled={page === 0}
                      onClick={() => setPage((p) => p - 1)}
                    >
                      Previous
                    </button>
                    <button
                      disabled={page + 1 >= data.totalPages}
                      onClick={() => setPage((p) => p + 1)}
                    >
                      Next
                    </button>
                  </div>
                </div>
              </>
            )}
          </section>
        )}
        <footer>
          Local evidence. Human-reviewed actions.{" "}
          <span>
            Monitoring links open in a new tab; observability services must be
            running.
          </span>
        </footer>
      </main>
    </>
  );
}
createRoot(document.getElementById("root")!).render(<App />);
